//! Trusted system-image build tool. Never executes Wasm or reads native artifacts.
use anyhow::{Context, Result, bail};
use ming_app_host::{
    desktop_catalog::load_catalog, engine::precompile_system_module, package::load_package,
};
use serde::Serialize;
use std::{
    fs::{self, OpenOptions},
    io::Write,
    path::{Path, PathBuf},
};

const TARGET: &str = "x86_64-unknown-linux-gnu";

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct OutputFile {
    file: String,
    bytes: usize,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct AppOutput {
    app_id: u16,
    package_id: String,
    manifest: PathBuf,
    sdk_version: u32,
    source: OutputFile,
    native: OutputFile,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct BuildManifest {
    schema_version: u32,
    catalog: PathBuf,
    target: &'static str,
    compiler_package: &'static str,
    compiler_version: &'static str,
    wasmtime_version: &'static str,
    engine_configuration: &'static str,
    optimization: &'static str,
    native_format: &'static str,
    table: &'static str,
    apps: Vec<AppOutput>,
}

// Retain the exact source Vec passed to the compiler and written to disk.
struct CompiledModule {
    sdk_version: u32,
    source: Vec<u8>,
    native_bytes: usize,
}

fn find_module(modules: &[CompiledModule], sdk: u32, source: &[u8]) -> Option<usize> {
    // Full byte equality plus SDK is the key; no fingerprint is trusted.
    modules
        .iter()
        .position(|module| module.sdk_version == sdk && module.source.as_slice() == source)
}

fn create_output_dir(path: &Path) -> Result<()> {
    // create_dir atomically rejects existing directories, files and symlinks.
    // Never reuse a partial output from a previous invocation.
    fs::create_dir(path).with_context(|| {
        format!("SYSTEM_PRECOMPILE_NEW_OUTPUT_REQUIRED: {}", path.display())
    })
}

fn write_new(path: &Path, bytes: &[u8]) -> Result<()> {
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .with_context(|| format!("SYSTEM_PRECOMPILE_CREATE_NEW: {}", path.display()))?;
    file.write_all(bytes)
        .with_context(|| format!("SYSTEM_PRECOMPILE_WRITE: {}", path.display()))
}

fn render_table(sdks: &[u32]) -> Result<String> {
    let mut table = String::from(
        "// Generated by precompile_system; trusted system-image build input.\n\
         const SYSTEM_MODULES: &[SystemModule] = &[\n",
    );
    for (offset, sdk) in sdks.iter().enumerate() {
        if !matches!(*sdk, 1..=6) {
            bail!("SYSTEM_PRECOMPILE_SDK_UNSUPPORTED: {sdk}");
        }
        let index = offset + 1;
        // No catalog strings or input paths can enter generated Rust source.
        table.push_str(&format!(
            "    SystemModule {{ sdk_version: {sdk}, source: include_bytes!(\"system_module_data/{index}.wasm\"), native_code: include_bytes!(\"system_module_data/{index}.cwasm\") }},\n"
        ));
    }
    table.push_str("];\n");
    Ok(table)
}

fn build(catalog_path: &Path, output_dir: &Path) -> Result<()> {
    if !cfg!(all(target_os = "linux", target_arch = "x86_64", target_env = "gnu")) {
        bail!("SYSTEM_PRECOMPILE_TARGET: requires Linux x86_64 GNU ({TARGET})");
    }
    let catalog = load_catalog(catalog_path).context("SYSTEM_PRECOMPILE_CATALOG")?;
    create_output_dir(output_dir)?;
    fs::create_dir(output_dir.join("system_module_data"))
        .context("SYSTEM_PRECOMPILE_DATA_DIRECTORY")?;
    let mut apps = Vec::with_capacity(catalog.apps.len());
    let mut modules = Vec::with_capacity(catalog.apps.len());
    for app in &catalog.apps {
        let package = load_package(&app.manifest_path)
            .with_context(|| format!("SYSTEM_PRECOMPILE_PACKAGE: catalog app {}", app.id))?;
        let sdk = package.manifest.sdk_version;
        if !matches!(sdk, 1..=6) {
            bail!("SYSTEM_PRECOMPILE_SDK_UNSUPPORTED: {sdk}");
        }
        let module_index = if let Some(index) = find_module(&modules, sdk, &package.bytes) {
            index
        } else {
            // Only this API produces native bytes; no Store or guest execution.
            let native = precompile_system_module(&package.bytes, sdk)
                .with_context(|| format!("SYSTEM_PRECOMPILE_MODULE: catalog app {}", app.id))?;
            let index = modules.len() + 1;
            // Compile and write raw from the same loaded Vec and SDK, without rereading.
            write_new(
                &output_dir.join(format!("system_module_data/{index}.wasm")),
                &package.bytes,
            )?;
            write_new(
                &output_dir.join(format!("system_module_data/{index}.cwasm")),
                &native,
            )?;
            modules.push(CompiledModule {
                sdk_version: sdk,
                source: package.bytes,
                native_bytes: native.len(),
            });
            modules.len() - 1
        };
        let module = &modules[module_index];
        let index = module_index + 1;
        let source_file = format!("system_module_data/{index}.wasm");
        let native_file = format!("system_module_data/{index}.cwasm");
        apps.push(AppOutput {
            app_id: app.id,
            package_id: package.manifest.id,
            manifest: app.manifest_path.clone(),
            sdk_version: sdk,
            source: OutputFile {
                file: source_file,
                bytes: module.source.len(),
            },
            native: OutputFile {
                file: native_file,
                bytes: module.native_bytes,
            },
        });
    }
    let sdks: Vec<_> = modules.iter().map(|module| module.sdk_version).collect();
    let table = render_table(&sdks)?;
    write_new(&output_dir.join("system_module_table.rs"), table.as_bytes())?;
    let manifest = BuildManifest {
        schema_version: 1,
        catalog: catalog_path.to_path_buf(),
        target: TARGET,
        compiler_package: env!("CARGO_PKG_NAME"),
        compiler_version: env!("CARGO_PKG_VERSION"),
        wasmtime_version: "50.0.0",
        engine_configuration: "engine::module_engine_config(true)",
        optimization: "Speed",
        native_format: "wasmtime::Module::serialize",
        table: "system_module_table.rs",
        apps,
    };
    // Write the manifest last; a failed invocation leaves inspectable partial output.
    let mut json = serde_json::to_vec_pretty(&manifest).context("SYSTEM_PRECOMPILE_MANIFEST")?;
    json.push(b'\n');
    write_new(&output_dir.join("manifest.json"), &json)?;
    println!(
        "Precompiled {} unique modules for {} catalog apps into {}",
        modules.len(),
        manifest.apps.len(),
        output_dir.display()
    );
    Ok(())
}

fn main() -> Result<()> {
    let mut args = std::env::args_os().skip(1);
    let (Some(catalog), Some(output)) = (args.next(), args.next()) else {
        bail!("usage: precompile_system <catalog.json> <new-output-dir>");
    };
    if args.next().is_some() {
        bail!("usage: precompile_system <catalog.json> <new-output-dir>");
    }
    build(Path::new(&catalog), Path::new(&output))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_uses_fixed_numeric_paths_and_private_registry_fields() {
        assert_eq!(render_table(&[1, 6]).unwrap(), concat!(
            "// Generated by precompile_system; trusted system-image build input.\n",
            "const SYSTEM_MODULES: &[SystemModule] = &[\n",
            "    SystemModule { sdk_version: 1, source: include_bytes!(\"system_module_data/1.wasm\"), native_code: include_bytes!(\"system_module_data/1.cwasm\") },\n",
            "    SystemModule { sdk_version: 6, source: include_bytes!(\"system_module_data/2.wasm\"), native_code: include_bytes!(\"system_module_data/2.cwasm\") },\n",
            "];\n",
        ));
        assert!(render_table(&[0]).is_err());
        assert!(render_table(&[7]).is_err());
    }

    #[test]
    fn duplicate_key_requires_the_same_sdk_and_every_source_byte() {
        let source = b"same source".to_vec();
        let modules = vec![CompiledModule {
            sdk_version: 6,
            source: source.clone(),
            native_bytes: 123,
        }];
        // An independently allocated Vec with identical bytes reuses the same entry.
        assert_eq!(find_module(&modules, 6, &source), Some(0));
        assert_eq!(find_module(&modules, 5, &source), None);
        let mut changed = source.clone();
        *changed.last_mut().unwrap() ^= 1;
        assert_eq!(find_module(&modules, 6, &changed), None);
        assert_eq!(find_module(&modules, 6, &source[..source.len() - 1]), None);
    }

    #[test]
    fn output_requires_a_new_directory_and_preserves_existing_content() {
        let temp = tempfile::tempdir().unwrap();
        let output = temp.path().join("output");
        create_output_dir(&output).unwrap();
        assert!(create_output_dir(&output).is_err());
        let sentinel = output.join("sentinel");
        write_new(&sentinel, b"keep").unwrap();
        assert!(create_output_dir(&output).is_err());
        assert!(create_output_dir(&sentinel).is_err());
        assert_eq!(fs::read(sentinel).unwrap(), b"keep");
    }

    #[test]
    fn output_file_cannot_be_overwritten() {
        let temp = tempfile::tempdir().unwrap();
        let path = temp.path().join("1.wasm");
        write_new(&path, b"original").unwrap();
        assert!(write_new(&path, b"replacement").is_err());
        assert_eq!(fs::read(path).unwrap(), b"original");
    }

    #[cfg(unix)]
    #[test]
    fn output_rejects_dangling_symlinks() {
        use std::os::unix::fs::symlink;
        let temp = tempfile::tempdir().unwrap();
        let missing = temp.path().join("missing");
        let link = temp.path().join("output");
        symlink(&missing, &link).unwrap();
        assert!(create_output_dir(&link).is_err());
        assert!(write_new(&link, b"replacement").is_err());
        assert!(fs::symlink_metadata(&link).unwrap().file_type().is_symlink());
        assert!(!missing.exists());
    }
}
